#!/usr/bin/env python3
"""fe_read_dma_selftest.py — prove the C97 READ-DMA math in sony-bx510.c
without firing the emulator.

The model now serves a READ by decoding the CDB out of the mailbox words and
synthesising raw CD frames around the plain 2048-byte ISO sectors
(emulator-kit/sony-bx510.c, `bx510_fe_read`). Both halves are pure arithmetic,
so they can be tested on their own — the emulator run only proves the rest of
the plumbing.

This script extracts `bx510_fe_cdb`, `bx510_fe_cdb_is_read`,
`bx510_fe_cdb_nsec` and `bx510_cd_frame` VERBATIM from the model source, compiles
them with a small driver on the lab VM (the fixture ISO lives there), and checks:

  1. CDB decode — a READ(10) / READ(12) / READ CD packet image in w1..w3 decodes
     to the LBA and sector count the CDB carries (c97-read-path.md §4.1);
  2. frame synthesis — the 2352-byte frames match firebird-fixture.md §5.2
     md5-for-md5, and what the driver's own strip loop (mode = frame[0xf],
     payload at +16) leaves behind matches the §5.1 plain-path md5s.

Both oracles were derived independently (from the ISO + the driver's strip loop)
so a match here is a match with the guest's expectation, not with our own code.

Usage: python3 fe_read_dma_selftest.py        (Mac side; needs the lab VM up)
Exit:  0 = every check passed, 1 = a mismatch or a build/run failure.
"""
from __future__ import annotations

import hashlib
import pathlib
import re
import subprocess
import sys

REPO = pathlib.Path(__file__).resolve().parents[4]
MODEL = REPO / "emulator-kit" / "sony-bx510.c"
VM_SSH = ["ssh", "-o", "BatchMode=yes", "-p", "2222", "aftermath@10.20.0.18"]
VM_SCP = ["scp", "-o", "BatchMode=yes", "-P", "2222"]
VM_ISO = "/home/aftermath/sacd-verify/firebird.iso"

# firebird-fixture.md §5.2 (raw frames) and §5.1 (stripped payload), cnt sectors.
ORACLES = [
    # lba,     cnt, raw 2352 md5,                          stripped 2048 md5
    (16,       1, "b8f578e8806bf4debabc28f765281699", "c117ce4cef54ab625e33583156605721"),
    (510,      1, "e03d750071d75dfdb006b074a1897b21", "e56de1add53c90dd30cf9232b29ddc93"),
    (532104,   1, "149a9ff1432a87fec5e71656be195a95", "9ed18b47f67232ea972515df65cb6ac5"),
    (510,     10, "14690aec4e5333ebed530137f53d4f4a", "45ccd7dfbf433a79d28e877d7441677c"),
    (1064207,  1, "dfaefb598cdde300952201794e826bd7", "d1c54ec6c395d7092ce06f04705d33ae"),
]

# Header bytes the fixture doc records for the same LBAs (BCD MSF + mode).
HEADERS = {16: "00021601", 510: "00086001", 532104: "18165401", 1064207: "36313201"}


def extract(src: str, signature: str) -> str:
    """Pull one top-level function body out of the model, verbatim."""
    start = src.index(signature)
    end = src.index("\n}\n", start) + 3
    return src[start:end]


DRIVER = r"""
/* generated by decode/fe_read_dma_selftest.py — the helpers below are copied
 * verbatim out of emulator-kit/sony-bx510.c */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <stdbool.h>

#define CD_PAYLOAD 2048u
#define CD_FRAME   2352u

/* the only field the extracted helpers touch */
typedef struct { uint32_t fe_cmd[4]; } Bx510State;

%(helpers)s

static void pack(uint32_t w[3], const uint8_t cdb[12])
{
    unsigned i;
    for (i = 0; i < 12; i++) {
        w[i / 4] |= (uint32_t)cdb[i] << (8 * (i %% 4));
    }
}

static int decode_case(const char *name, const uint8_t cdb[12],
                       uint32_t want_lba, uint32_t want_nsec)
{
    Bx510State s = { { 0xa0000000u, 0, 0, 0 } };
    uint8_t back[12];
    uint32_t lba, nsec;

    pack(&s.fe_cmd[1], cdb);
    bx510_fe_cdb(&s, back);
    if (memcmp(back, cdb, 12) != 0 || !bx510_fe_cdb_is_read(back)) {
        printf("DECODE %%-10s FAIL cdb round-trip/is-read\n", name);
        return 1;
    }
    lba = ((uint32_t)back[2] << 24) | ((uint32_t)back[3] << 16) |
          ((uint32_t)back[4] << 8) | back[5];
    nsec = bx510_fe_cdb_nsec(back);
    printf("DECODE %%-10s lba=%%u nsec=%%u %%s\n", name, lba, nsec,
           (lba == want_lba && nsec == want_nsec) ? "PASS" : "FAIL");
    return (lba == want_lba && nsec == want_nsec) ? 0 : 1;
}

int main(int argc, char **argv)
{
    const char *iso = argv[1], *outdir = argv[2];
    uint8_t cdb[12];
    char path[512];
    FILE *in, *f;
    int bad = 0;
    unsigned o;

    /* 1. CDB decode, all three opcodes (c97-read-path.md §4.1) */
    memset(cdb, 0, sizeof(cdb));
    cdb[0] = 0x28; cdb[2] = 0x00; cdb[3] = 0x00; cdb[4] = 0x01; cdb[5] = 0xfe;
    cdb[7] = 0x00; cdb[8] = 0x0a;                       /* READ(10)  lba 510, 10 */
    bad |= decode_case("read10", cdb, 510, 10);
    memset(cdb, 0, sizeof(cdb));
    cdb[0] = 0xa8; cdb[2] = 0x00; cdb[3] = 0x08; cdb[4] = 0x1e; cdb[5] = 0x88;
    cdb[6] = 0x00; cdb[7] = 0x00; cdb[8] = 0x00; cdb[9] = 0x20;  /* READ(12) */
    bad |= decode_case("read12", cdb, 532104, 32);
    memset(cdb, 0, sizeof(cdb));
    cdb[0] = 0xbe; cdb[2] = 0x00; cdb[3] = 0x00; cdb[4] = 0x01; cdb[5] = 0xfe;
    cdb[6] = 0x00; cdb[7] = 0x00; cdb[8] = 0x01; cdb[9] = 0xf8;  /* READ CD */
    bad |= decode_case("readcd", cdb, 510, 1);

    /* 2. frame synthesis against the fixture oracles */
    in = fopen(iso, "rb");
    if (!in) { perror(iso); return 1; }
    for (o = 0; o < %(ncases)d; o++) {
        uint32_t lba = %(lbas)s[o], cnt = %(cnts)s[o], i;
        uint8_t *plain = malloc((size_t)cnt * CD_PAYLOAD);
        uint8_t *raw = malloc((size_t)cnt * CD_FRAME);
        uint8_t *strip = malloc((size_t)cnt * CD_PAYLOAD);

        if (fseeko(in, (off_t)lba * CD_PAYLOAD, SEEK_SET) ||
            fread(plain, CD_PAYLOAD, cnt, in) != cnt) {
            printf("FRAME  lba=%%u FAIL read\n", lba);
            return 1;
        }
        for (i = 0; i < cnt; i++) {
            uint8_t *fr = raw + (size_t)i * CD_FRAME;
            uint8_t *pl = plain + (size_t)i * CD_PAYLOAD;

            bx510_cd_frame(fr, pl, lba + i);
            /* the driver's own strip loop, data_xfer .text+0x54ac..0x54f8 */
            memcpy(strip + (size_t)i * CD_PAYLOAD,
                   fr + (fr[0xf] == 2 ? 24 : 16), CD_PAYLOAD);
        }
        snprintf(path, sizeof(path), "%%s/%%u_%%u.hdr", outdir, lba, cnt);
        f = fopen(path, "wb");
        for (i = 0; i < cnt; i++) {
            fwrite(raw + (size_t)i * CD_FRAME + 12, 1, 4, f);
        }
        fclose(f);
        snprintf(path, sizeof(path), "%%s/%%u_%%u.raw", outdir, lba, cnt);
        f = fopen(path, "wb"); fwrite(raw, 1, (size_t)cnt * CD_FRAME, f); fclose(f);
        snprintf(path, sizeof(path), "%%s/%%u_%%u.strip", outdir, lba, cnt);
        f = fopen(path, "wb"); fwrite(strip, 1, (size_t)cnt * CD_PAYLOAD, f); fclose(f);
        printf("FRAME  lba=%%u cnt=%%u written\n", lba, cnt);
        free(plain); free(raw); free(strip);
    }
    fclose(in);
    return bad;
}
"""


def main() -> int:
    src = MODEL.read_text()
    helpers = "\n\n".join(
        extract(src, sig) for sig in (
            "static void bx510_fe_cdb(",
            "static bool bx510_fe_cdb_is_read(",
            "static uint32_t bx510_fe_cdb_nsec(",
            "static void bx510_cd_frame(",
        )
    )
    c_src = DRIVER % {
        "helpers": helpers,
        "ncases": len(ORACLES),
        "lbas": "(const uint32_t[]){ " + ", ".join(str(o[0]) for o in ORACLES) + " }",
        "cnts": "(const uint32_t[]){ " + ", ".join(str(o[1]) for o in ORACLES) + " }",
    }
    local = pathlib.Path("/tmp/fe_read_dma_selftest.c")
    local.write_text(c_src)

    run = f"""
set -e
gcc -std=gnu99 -O1 -Wall -o /tmp/fe_read_dma_selftest /tmp/fe_read_dma_selftest.c
rm -rf /tmp/fedma; mkdir -p /tmp/fedma
/tmp/fe_read_dma_selftest {VM_ISO} /tmp/fedma
cd /tmp/fedma && md5sum *.raw *.strip *.hdr
"""
    pathlib.Path("/tmp/fe_read_dma_selftest.sh").write_text(run)
    subprocess.run(VM_SCP + ["/tmp/fe_read_dma_selftest.c",
                             "aftermath@10.20.0.18:/tmp/"], check=True)
    subprocess.run(VM_SCP + ["/tmp/fe_read_dma_selftest.sh",
                             "aftermath@10.20.0.18:/tmp/"], check=True)
    out = subprocess.run(VM_SSH + ["sh /tmp/fe_read_dma_selftest.sh"],
                         capture_output=True, text=True)
    print(out.stdout, end="")
    if out.returncode != 0:
        print(out.stderr, end="", file=sys.stderr)
        return 1

    got = {}
    for line in out.stdout.splitlines():
        m = re.match(r"^([0-9a-f]{32})\s+(\S+)$", line)
        if m:
            got[m.group(2)] = m.group(1)
    fails = []
    for lba, cnt, raw_md5, strip_md5 in ORACLES:
        for suffix, want in (("raw", raw_md5), ("strip", strip_md5)):
            name = f"{lba}_{cnt}.{suffix}"
            if got.get(name) != want:
                fails.append(f"{name}: got {got.get(name)} want {want}")
        # The fixture records the header of one LBA only, so the header check is
        # for the single-sector rows (a batch's later sectors have their own
        # MSF by construction).
        if cnt == 1:
            hdr = got.get(f"{lba}_{cnt}.hdr")
            exp = HEADERS[lba]
            digest = hashlib.md5(bytes.fromhex(exp)).hexdigest()
            if hdr != digest:
                fails.append(f"{lba}_{cnt}.hdr: got {hdr} want {digest} "
                             f"(header {exp})")
    if fails:
        print("\nSELFTEST FAIL")
        for f_ in fails:
            print("  " + f_)
        return 1
    print(f"\nSELFTEST PASS — {len(ORACLES)} raw frames + stripped payloads + "
          f"headers, 3 CDB decode cases")
    return 0


if __name__ == "__main__":
    sys.exit(main())
